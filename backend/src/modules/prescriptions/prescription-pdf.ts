import PDFDocument from 'pdfkit';
import { Prescription } from './entities/prescription.entity.js';

// Simple one-page prescription (spec 3F): platform name, doctor, patient,
// date, diagnosis, medicines (dosage, frequency, duration) and advice.
export function renderPrescriptionPdf(p: Prescription): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50, info: { Title: `Prescription ${p.id}` } });
    const chunks: Buffer[] = [];

    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const doctor = p.doctor;
    const patient = p.patient;
    const date = p.appointment?.appointmentDate ?? p.createdAt.toISOString().slice(0, 10);

    doc.fontSize(20).fillColor('#0b5394').text('MediPulse', { continued: true })
      .fontSize(10).fillColor('#666666').text('   Digital prescription');
    doc.moveDown(0.3).strokeColor('#cccccc').moveTo(50, doc.y).lineTo(545, doc.y).stroke();
    doc.moveDown();

    doc.fillColor('#000000').fontSize(11);
    doc.font('Helvetica-Bold').text(`Dr. ${doctor.user.fullName.replace(/^Dr\.?\s*/i, '')}`);
    doc.font('Helvetica').text(`${doctor.specialization?.name ?? ''}  |  ${doctor.qualifications}`);
    if (doctor.user.phone) doc.text(`Phone: ${doctor.user.phone}`);
    doc.moveDown();

    doc.font('Helvetica-Bold').text('Patient: ', { continued: true }).font('Helvetica')
      .text(`${patient.user.fullName}  (ID ${patient.patientCode})`);
    const details = [
      patient.gender ? `Gender: ${patient.gender}` : null,
      patient.dateOfBirth ? `Date of birth: ${patient.dateOfBirth}` : null,
      patient.bloodGroup ? `Blood group: ${patient.bloodGroup}` : null,
    ].filter(Boolean);
    if (details.length) doc.text(details.join('   '));
    doc.font('Helvetica-Bold').text('Date: ', { continued: true }).font('Helvetica').text(date);
    doc.moveDown();

    doc.font('Helvetica-Bold').fontSize(12).text('Diagnosis');
    doc.font('Helvetica').fontSize(11).text(p.diagnosis);
    doc.moveDown();

    doc.font('Helvetica-Bold').fontSize(12).text('Medicines');
    doc.fontSize(11);
    (p.medicines ?? []).forEach((m, i) => {
      doc.font('Helvetica-Bold').text(`${i + 1}. ${m.medicineName}`, { continued: true })
        .font('Helvetica').text(`  ${m.dosage}`);
      doc.text(`    ${m.frequency}  |  ${m.duration}`);
      if (m.instructions) doc.fillColor('#555555').text(`    ${m.instructions}`).fillColor('#000000');
    });
    doc.moveDown();

    if (p.advice) {
      doc.font('Helvetica-Bold').fontSize(12).text('Advice');
      doc.font('Helvetica').fontSize(11).text(p.advice);
      doc.moveDown();
    }

    if (p.followUpDate) {
      doc.font('Helvetica-Bold').text('Follow-up: ', { continued: true }).font('Helvetica').text(p.followUpDate);
    }

    doc.moveDown(2).fontSize(8).fillColor('#888888')
      .text(`Prescription ID ${p.id}. Generated by MediPulse.`, { align: 'center' });

    doc.end();
  });
}
